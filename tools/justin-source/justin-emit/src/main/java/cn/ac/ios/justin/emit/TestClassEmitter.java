package cn.ac.ios.justin.emit;

import cn.ac.ios.justin.core.target.ClassTarget;
import cn.ac.ios.justin.core.target.MethodTarget;
import cn.ac.ios.justin.core.test.Assertion;
import cn.ac.ios.justin.core.test.Statement;
import cn.ac.ios.justin.core.test.TestCase;
import com.palantir.javapoet.AnnotationSpec;
import com.palantir.javapoet.ClassName;
import com.palantir.javapoet.CodeBlock;
import com.palantir.javapoet.JavaFile;
import com.palantir.javapoet.MethodSpec;
import com.palantir.javapoet.TypeName;
import com.palantir.javapoet.TypeSpec;

import javax.lang.model.element.Modifier;
import java.io.IOException;
import java.nio.file.Path;
import java.util.List;

/** Renders the TestCases of one class as a JUnit 5 test class named &lt;Simple&gt;JustinTest in the same package. */
public final class TestClassEmitter {

    public static final String SUFFIX = "JustinTest";
    private static final ClassName TEST = ClassName.get("org.junit.jupiter.api", "Test");
    private static final ClassName TIMEOUT = ClassName.get("org.junit.jupiter.api", "Timeout");
    private static final ClassName TAG = ClassName.get("org.junit.jupiter.api", "Tag");
    private static final ClassName ASSERTIONS = ClassName.get("org.junit.jupiter.api", "Assertions");

    private final long timeoutSeconds;

    public TestClassEmitter(long timeoutSeconds) { this.timeoutSeconds = timeoutSeconds; }

    public static String testClassName(ClassTarget target) {
        return target.binaryName().substring(target.binaryName().lastIndexOf('.') + 1).replace('$', '_') + SUFFIX;
    }

    public JavaFile emit(ClassTarget target, List<TestCase> tests) {
        TypeSpec.Builder cls = TypeSpec.classBuilder(testClassName(target))
                .addModifiers(Modifier.PUBLIC)
                .addJavadoc("Generated by Justin for $L. Do not edit; regenerate instead.\n", target.binaryName().replace('$', '.'));
        for (TestCase tc : tests) cls.addMethod(method(tc));
        return JavaFile.builder(target.packageName(), cls.build())
                .addStaticImport(ASSERTIONS, "*")
                .skipJavaLangImports(true)
                .indent("    ")
                .build();
    }

    public Path write(JavaFile file, Path srcRoot) throws IOException {
        file.writeTo(srcRoot);
        return srcRoot.resolve(file.packageName().replace('.', '/')).resolve(file.typeSpec().name() + ".java");
    }

    private MethodSpec method(TestCase tc) {
        MethodSpec.Builder m = MethodSpec.methodBuilder(tc.name())
                .addModifiers(Modifier.PUBLIC)
                .addAnnotation(TEST)
                .addAnnotation(AnnotationSpec.builder(TIMEOUT).addMember("value", "$L", timeoutSeconds).build())
                .addException(ClassName.get("java.lang", "Throwable"))
                .addJavadoc("Target: $L\nStrategy: $L, seed $L, source $L\n", tc.target().display(), tc.strategy(), tc.seed(), tc.input().source());
        if (tc.verdict() != null) {
            m.addJavadoc("Exception verdict: $L ($L)\n", tc.verdict().kind(), tc.verdict().evidence());
            if (tc.isSuspect()) m.addAnnotation(AnnotationSpec.builder(TAG).addMember("value", "$S", "justin-suspect").build());
        }
        for (Statement s : tc.statements()) m.addCode(statement(s));
        return m.build();
    }

    private CodeBlock statement(Statement s) {
        if (s instanceof Statement.Declare d) {
            return CodeBlock.of("$T $L = $L;\n", TypeNames.of(d.type()), d.var(), ValueCode.of(d.value()));
        }
        if (s instanceof Statement.Invoke inv) {
            CodeBlock call = call(inv);
            if (inv.resultVar() == null) return CodeBlock.of("$L;\n", call);
            return CodeBlock.of("$T $L = $L;\n", TypeNames.of(inv.resultType()), inv.resultVar(), call);
        }
        if (s instanceof Statement.Assert a) return assertion(a.assertion());
        throw new IllegalArgumentException("unknown statement " + s);
    }

    private CodeBlock call(Statement.Invoke inv) {
        MethodTarget m = inv.method();
        CodeBlock args = ValueCode.args(inv.args());
        if (m.isConstructor()) return CodeBlock.of("new $T($L)", TypeNames.className(m.declaringClass()), args);
        if (m.isStatic()) return CodeBlock.of("$T.$L($L)", TypeNames.className(m.declaringClass()), m.name(), args);
        return CodeBlock.of("$L.$L($L)", inv.receiverVar(), m.name(), args);
    }

    private CodeBlock assertion(Assertion a) {
        if (a instanceof Assertion.Equals e) {
            if (e.delta() != null) return CodeBlock.of("assertEquals($L, $L, $LD);\n", ValueCode.of(e.expected()), e.actualVar(), e.delta());
            return CodeBlock.of("assertEquals($L, $L);\n", ValueCode.of(e.expected()), e.actualVar());
        }
        if (a instanceof Assertion.ArrayEquals e) {
            if (e.castTo() != null) return CodeBlock.of("assertArrayEquals($L, ($T) $L);\n", ValueCode.of(e.expected()), TypeNames.raw(e.castTo()), e.actualVar());
            return CodeBlock.of("assertArrayEquals($L, $L);\n", ValueCode.of(e.expected()), e.actualVar());
        }
        if (a instanceof Assertion.IsNull n) return CodeBlock.of("assertNull($L);\n", n.actualVar());
        if (a instanceof Assertion.NotNull n) return CodeBlock.of("assertNotNull($L);\n", n.actualVar());
        if (a instanceof Assertion.IsTrue t) return CodeBlock.of("assertTrue($L);\n", t.actualVar());
        if (a instanceof Assertion.IsFalse f) return CodeBlock.of("assertFalse($L);\n", f.actualVar());
        if (a instanceof Assertion.Condition c) return CodeBlock.of("assertTrue($L, $S);\n", c.expression(), c.message());
        if (a instanceof Assertion.Throws t) {
            TypeName ex = TypeNames.className(t.exceptionClass());
            return CodeBlock.of("assertThrows($T.class, () -> $L);\n", ex, call(t.invoke()));
        }
        throw new IllegalArgumentException("unknown assertion " + a);
    }
}
